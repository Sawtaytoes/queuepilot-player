#!/usr/bin/env python3
"""Convert the vendored Lucide SVGs into Android VectorDrawables.

Usage: tools/lucide/generate.py
Reads tools/lucide/svg/<name>.svg and writes
android/app/src/main/res/drawable/lucide_<name>.xml. Every icon keeps Lucide's single
2-unit stroke with round caps and joins, drawn in white so a view tints it with an existing
color. VectorDrawable has no circle, rect, line, polyline or polygon element, so those
shapes become equivalent path data.
"""
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent.parent / 'android/app/src/main/res/drawable'
SVG = '{http://www.w3.org/2000/svg}'


def number(value):
    text = f'{float(value):.4f}'.rstrip('0').rstrip('.')
    return text if text not in ('', '-0') else '0'


def attr(element, name, default='0'):
    return float(element.get(name, default))


def circle(cx, cy, rx, ry):
    return (
        f'M{number(cx - rx)},{number(cy)}'
        f'a{number(rx)},{number(ry)} 0 1,0 {number(2 * rx)},0'
        f'a{number(rx)},{number(ry)} 0 1,0 {number(-2 * rx)},0z'
    )


def rect(element):
    x, y = attr(element, 'x'), attr(element, 'y')
    width, height = attr(element, 'width'), attr(element, 'height')
    rx = element.get('rx', element.get('ry'))
    ry = element.get('ry', element.get('rx'))
    rx = min(float(rx or 0), width / 2)
    ry = min(float(ry or 0), height / 2)
    if rx == 0 or ry == 0:
        return f'M{number(x)},{number(y)}h{number(width)}v{number(height)}h{number(-width)}z'
    return (
        f'M{number(x + rx)},{number(y)}'
        f'h{number(width - 2 * rx)}a{number(rx)},{number(ry)} 0 0,1 {number(rx)},{number(ry)}'
        f'v{number(height - 2 * ry)}a{number(rx)},{number(ry)} 0 0,1 {number(-rx)},{number(ry)}'
        f'h{number(2 * rx - width)}a{number(rx)},{number(ry)} 0 0,1 {number(-rx)},{number(-ry)}'
        f'v{number(2 * ry - height)}a{number(rx)},{number(ry)} 0 0,1 {number(rx)},{number(-ry)}z'
    )


def points(element, is_closed):
    values = [number(v) for v in re.split(r'[\s,]+', element.get('points', '').strip()) if v]
    pairs = [f'{values[i]},{values[i + 1]}' for i in range(0, len(values) - 1, 2)]
    return 'M' + 'L'.join(pairs) + ('z' if is_closed else '')


def path_data(element):
    tag = element.tag.removeprefix(SVG)
    if tag == 'path':
        return element.get('d')
    if tag == 'circle':
        r = attr(element, 'r')
        return circle(attr(element, 'cx'), attr(element, 'cy'), r, r)
    if tag == 'ellipse':
        return circle(attr(element, 'cx'), attr(element, 'cy'), attr(element, 'rx'), attr(element, 'ry'))
    if tag == 'rect':
        return rect(element)
    if tag == 'line':
        return (
            f'M{number(attr(element, "x1"))},{number(attr(element, "y1"))}'
            f'L{number(attr(element, "x2"))},{number(attr(element, "y2"))}'
        )
    if tag in ('polyline', 'polygon'):
        return points(element, tag == 'polygon')
    raise ValueError(f'Unsupported SVG element: {tag}')


def drawable(source):
    root = ET.parse(source).getroot()
    assert root.get('viewBox') == '0 0 24 24', source
    assert root.get('stroke-width') == '2', source
    paths = [path_data(e) for e in root if e.tag.removeprefix(SVG) != 'title']
    body = ''.join(
        f'\n  <path\n      android:pathData="{d}"\n      android:fillColor="#00000000"'
        '\n      android:strokeColor="#FFFFFFFF"\n      android:strokeWidth="2"'
        '\n      android:strokeLineCap="round"\n      android:strokeLineJoin="round" />'
        for d in paths
    )
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f'<!-- Generated by tools/lucide/generate.py from Lucide "{source.stem}" (ISC). Do not edit. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="24dp"\n    android:height="24dp"\n'
        '    android:viewportWidth="24"\n    android:viewportHeight="24">'
        f'{body}\n</vector>\n'
    )


def main():
    names = [
        line.strip()
        for line in (HERE / 'icons.txt').read_text().splitlines()
        if line.strip() and not line.startswith('#')
    ]
    OUT.mkdir(parents=True, exist_ok=True)
    for stale in OUT.glob('lucide_*.xml'):
        stale.unlink()
    for name in names:
        target = OUT / f'lucide_{name.replace("-", "_")}.xml'
        target.write_text(drawable(HERE / 'svg' / f'{name}.svg'))
    print(f'Wrote {len(names)} drawables to {OUT}')


if __name__ == '__main__':
    sys.exit(main())
